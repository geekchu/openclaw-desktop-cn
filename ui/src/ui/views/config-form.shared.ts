export function humanize(raw: string) {
  // 首先检查是否有直接翻译
  if (FIELD_TRANSLATIONS[raw]) {
    return FIELD_TRANSLATIONS[raw];
  }

  // 检查小写版本
  const lowerRaw = raw.toLowerCase();
  if (FIELD_TRANSLATIONS[lowerRaw]) {
    return FIELD_TRANSLATIONS[lowerRaw];
  }

  // 如果没有翻译，返回原始的英文格式化结果
  return raw
    .replace(/_/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .replace(/^./, (m) => m.toUpperCase());
}
